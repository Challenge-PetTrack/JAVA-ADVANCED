CREATE OR REPLACE PACKAGE PKG_PETTRACK_LOG AS
PROCEDURE PRC_INSERT_LOG_ERRO(
    P_NM_PROCEDURE IN TB_LOG_ERRO.NM_PROCEDURE%TYPE,
    P_CD_ERRO      IN TB_LOG_ERRO.CD_ERRO%TYPE,
    P_DS_MENSAGEM  IN TB_LOG_ERRO.DS_MENSAGEM%TYPE
);
END PKG_PETTRACK_LOG;
/

CREATE OR REPLACE PACKAGE BODY PKG_PETTRACK_LOG AS
PROCEDURE PRC_INSERT_LOG_ERRO(
    P_NM_PROCEDURE IN TB_LOG_ERRO.NM_PROCEDURE%TYPE,
    P_CD_ERRO      IN TB_LOG_ERRO.CD_ERRO%TYPE,
    P_DS_MENSAGEM  IN TB_LOG_ERRO.DS_MENSAGEM%TYPE
)
IS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO TB_LOG_ERRO (ID_LOG, NM_PROCEDURE, NM_USUARIO, DT_OCORRENCIA, CD_ERRO, DS_MENSAGEM) 
        VALUES (SEQ_LOG_ERRO.NEXTVAL, P_NM_PROCEDURE, USER, SYSDATE, P_CD_ERRO, P_DS_MENSAGEM);
    COMMIT;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK;
    WHEN VALUE_ERROR THEN
        ROLLBACK;
    WHEN OTHERS THEN
        ROLLBACK;
END PRC_INSERT_LOG_ERRO;
END PKG_PETTRACK_LOG;
/

