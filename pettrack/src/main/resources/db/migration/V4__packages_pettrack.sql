    -- Serializacao manual: escapes JSON completos e numeros independentes de NLS.
FUNCTION TEXTO_JSON(P_TEXTO IN VARCHAR2) RETURN VARCHAR2 IS
    V_TEXTO VARCHAR2(32767);
BEGIN
    IF P_TEXTO IS NULL THEN RETURN 'null'; END IF;
    V_TEXTO := REPLACE(REPLACE(P_TEXTO, '\', '\\'), '"', '\"');
    FOR I IN 0..31 LOOP
        V_TEXTO := REPLACE(V_TEXTO, CHR(I), '\u00' || LPAD(TO_CHAR(I, 'FMXX'), 2, '0'));
    END LOOP;
    RETURN '"' || V_TEXTO || '"';
END;
FUNCTION NUMERO_JSON(P_NUMERO IN NUMBER) RETURN VARCHAR2 IS
BEGIN
    IF P_NUMERO IS NULL THEN RETURN 'null'; END IF;
    RETURN TO_CHAR(P_NUMERO, 'TM9', 'NLS_NUMERIC_CHARACTERS=''.,''');
END;
PROCEDURE ADICIONAR(P_DESTINO IN OUT NOCOPY CLOB, P_TEXTO IN VARCHAR2) IS
BEGIN
    IF P_TEXTO IS NOT NULL THEN DBMS_LOB.WRITEAPPEND(P_DESTINO, LENGTH(P_TEXTO), P_TEXTO); END IF;
END;
