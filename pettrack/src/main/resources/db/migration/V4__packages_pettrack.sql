FUNCTION FN_CALCULAR_TAXA_ADESAO (
    P_ID_MEDICAMENTO IN NUMBER
) RETURN NUMBER
IS
    V_TOTAL_DOSES     NUMBER := 0;
    V_DOSES_TOMADAS   NUMBER := 0;
    V_TAXA_PERCENTUAL NUMBER(5,2) := 0;
    V_EXISTE_MED      NUMBER := 0;
    
    EX_MEDICAMENTO_INEXISTENTE EXCEPTION;
    EX_SEM_DOSES_REGISTRADAS   EXCEPTION;
BEGIN
    SELECT COUNT(1) INTO V_EXISTE_MED 
    FROM TB_MEDICAMENTO 
    WHERE ID_MEDICAMENTO = P_ID_MEDICAMENTO;

    IF V_EXISTE_MED = 0 THEN
        RAISE EX_MEDICAMENTO_INEXISTENTE;
    END IF;

    SELECT 
        COUNT(1),
        COUNT(CASE WHEN ST_TOMOU = 'S' THEN 1 END)
    INTO 
        V_TOTAL_DOSES,
        V_DOSES_TOMADAS
    FROM TB_ADESAO_MEDICAMENTO
    WHERE ID_MEDICAMENTO = P_ID_MEDICAMENTO;

    IF V_TOTAL_DOSES = 0 THEN
        RAISE EX_SEM_DOSES_REGISTRADAS;
    END IF;

    V_TAXA_PERCENTUAL := ROUND((V_DOSES_TOMADAS / V_TOTAL_DOSES) * 100, 2);
    RETURN V_TAXA_PERCENTUAL;

EXCEPTION
    WHEN EX_MEDICAMENTO_INEXISTENTE THEN
        PKG_PETTRACK_LOG.PRC_INSERT_LOG_ERRO('FN_CALCULAR_TAXA_ADESAO', -20010, 'Medicamento ID ' || P_ID_MEDICAMENTO || ' nao encontrado.');
        RETURN -1;

    WHEN EX_SEM_DOSES_REGISTRADAS THEN
        PKG_PETTRACK_LOG.PRC_INSERT_LOG_ERRO('FN_CALCULAR_TAXA_ADESAO', -20011, 'Nenhuma dose registrada para o medicamento ID ' || P_ID_MEDICAMENTO);
        RETURN 0;

    WHEN ZERO_DIVIDE THEN
        PKG_PETTRACK_LOG.PRC_INSERT_LOG_ERRO('FN_CALCULAR_TAXA_ADESAO', SQLCODE, 'Divisao por zero na taxa de adesao.');
        RETURN 0;

    WHEN OTHERS THEN
        PKG_PETTRACK_LOG.PRC_INSERT_LOG_ERRO('FN_CALCULAR_TAXA_ADESAO', SQLCODE, SQLERRM);
        RETURN -99;
END FN_CALCULAR_TAXA_ADESAO;

PROCEDURE PRC_LISTAR_PETS_JSON (
    P_DS_ESPECIE IN VARCHAR2, P_DATASET OUT CLOB
) IS
    V_PRIMEIRO BOOLEAN := TRUE;
BEGIN
    IF P_DS_ESPECIE IS NOT NULL AND LENGTH(TRIM(P_DS_ESPECIE)) < 2 THEN
        RAISE_APPLICATION_ERROR(-20020, 'Filtro de especie invalido.');
    END IF;
    DBMS_LOB.CREATETEMPORARY(P_DATASET, TRUE);
    ADICIONAR(P_DATASET, '[');
    FOR R IN (
        SELECT P.ID_PET, P.NM_PET, P.DS_ESPECIE, P.DS_RACA, P.NR_PESO_KG,
               P.ID_TUTOR, T.NM_TUTOR, P.ID_CLINICA, C.NM_CLINICA
        FROM TB_PET P JOIN TB_TUTOR T ON T.ID_TUTOR=P.ID_TUTOR
        JOIN TB_CLINICA C ON C.ID_CLINICA=P.ID_CLINICA
        WHERE P_DS_ESPECIE IS NULL OR UPPER(P.DS_ESPECIE)=UPPER(P_DS_ESPECIE)
        ORDER BY P.ID_PET
    ) LOOP
        IF NOT V_PRIMEIRO THEN ADICIONAR(P_DATASET, ','); END IF;
        V_PRIMEIRO := FALSE;
        ADICIONAR(P_DATASET, FN_MONTAR_JSON_PET(R.ID_PET, R.NM_PET, R.DS_ESPECIE,
            R.DS_RACA, R.NR_PESO_KG, R.NM_TUTOR, R.NM_CLINICA, R.ID_TUTOR, R.ID_CLINICA));
    END LOOP;
    ADICIONAR(P_DATASET, ']');
EXCEPTION WHEN OTHERS THEN
    IF DBMS_LOB.ISTEMPORARY(P_DATASET)=1 THEN DBMS_LOB.FREETEMPORARY(P_DATASET); END IF;
    PKG_PETTRACK_LOG.PRC_INSERT_LOG_ERRO('PKG_CONSULTA.PRC_LISTAR_PETS_JSON', SQLCODE, SQLERRM);
    RAISE;
END PRC_LISTAR_PETS_JSON;

PROCEDURE PRC_RELATORIO_SUBTOTAIS_MANUAL(P_RELATORIO OUT CLOB)
IS
    CURSOR C_FATOS IS
        SELECT 
            C.NM_CLINICA AS CATEGORIA_1,
            P.NM_PET     AS CATEGORIA_2,
            NVL(CL.NR_ATIVIDADE, 0) AS VALOR_NUMERICO
        FROM TB_COLLAR_LEITURA CL
        INNER JOIN TB_PET P     ON P.ID_PET = CL.ID_PET
        INNER JOIN TB_CLINICA C ON C.ID_CLINICA = P.ID_CLINICA
        ORDER BY C.NM_CLINICA, P.NM_PET;

    V_CAT1_ANTERIOR   TB_CLINICA.NM_CLINICA%TYPE := NULL;
    V_SUBTOTAL_CAT1   NUMBER(12,2) := 0;
    V_TOTAL_GERAL     NUMBER(12,2) := 0;
    V_TOTAL_LINHAS    NUMBER := 0;
    V_PRIMEIRA_LINHA  BOOLEAN := TRUE;

    EX_SEM_DADOS_FATOS EXCEPTION;
    EX_VALOR_NEGATIVO  EXCEPTION;
BEGIN
    DBMS_LOB.CREATETEMPORARY(P_RELATORIO, TRUE);
    ADICIONAR(P_RELATORIO, RPAD('Clinica', 35) || ' ' || RPAD('Pet', 20) || ' ' || LPAD('Atividade', 12) || CHR(10));
    ADICIONAR(P_RELATORIO, RPAD('-', 35, '-') || ' ' || RPAD('-', 20, '-') || ' ' || LPAD('-', 12, '-') || CHR(10));

    FOR REG IN C_FATOS LOOP
        V_TOTAL_LINHAS := V_TOTAL_LINHAS + 1;

        IF REG.VALOR_NUMERICO < 0 THEN
            RAISE EX_VALOR_NEGATIVO;
        END IF;

        IF NOT V_PRIMEIRA_LINHA AND REG.CATEGORIA_1 <> V_CAT1_ANTERIOR THEN
            ADICIONAR(P_RELATORIO, RPAD('Sub Total', 56) || ' ' || LPAD(TO_CHAR(V_SUBTOTAL_CAT1, 'FM999990.00'), 12) || CHR(10));
            V_SUBTOTAL_CAT1 := 0;
        END IF;

        ADICIONAR(P_RELATORIO, 
            RPAD(REG.CATEGORIA_1, 35) || ' ' ||
            RPAD(REG.CATEGORIA_2, 20) || ' ' ||
            LPAD(TO_CHAR(REG.VALOR_NUMERICO, 'FM999990.00'), 12)
         || CHR(10));

        V_SUBTOTAL_CAT1 := V_SUBTOTAL_CAT1 + REG.VALOR_NUMERICO;
        V_TOTAL_GERAL   := V_TOTAL_GERAL + REG.VALOR_NUMERICO;
        V_CAT1_ANTERIOR := REG.CATEGORIA_1;
        V_PRIMEIRA_LINHA := FALSE;
    END LOOP;

    IF V_TOTAL_LINHAS = 0 THEN
        RAISE EX_SEM_DADOS_FATOS;
    END IF;

    ADICIONAR(P_RELATORIO, RPAD('Sub Total', 56) || ' ' || LPAD(TO_CHAR(V_SUBTOTAL_CAT1, 'FM999990.00'), 12) || CHR(10));
    ADICIONAR(P_RELATORIO, RPAD('Total Geral', 56) || ' ' || LPAD(TO_CHAR(V_TOTAL_GERAL, 'FM999990.00'), 12) || CHR(10));

EXCEPTION
    WHEN EX_SEM_DADOS_FATOS THEN
        PKG_PETTRACK_LOG.PRC_INSERT_LOG_ERRO('PRC_RELATORIO_SUBTOTAIS_MANUAL', -20030, 'Sem dados para sumarização.');
        IF DBMS_LOB.ISTEMPORARY(P_RELATORIO)=1 THEN DBMS_LOB.FREETEMPORARY(P_RELATORIO); END IF;
        RAISE;

    WHEN EX_VALOR_NEGATIVO THEN
        PKG_PETTRACK_LOG.PRC_INSERT_LOG_ERRO('PRC_RELATORIO_SUBTOTAIS_MANUAL', -20031, 'Valor numérico inconsistente.');
        IF DBMS_LOB.ISTEMPORARY(P_RELATORIO)=1 THEN DBMS_LOB.FREETEMPORARY(P_RELATORIO); END IF;
        RAISE;

    WHEN VALUE_ERROR THEN
        PKG_PETTRACK_LOG.PRC_INSERT_LOG_ERRO('PRC_RELATORIO_SUBTOTAIS_MANUAL', SQLCODE, 'Erro de conversão numérica.');
        IF DBMS_LOB.ISTEMPORARY(P_RELATORIO)=1 THEN DBMS_LOB.FREETEMPORARY(P_RELATORIO); END IF;
        RAISE;

    WHEN OTHERS THEN
        PKG_PETTRACK_LOG.PRC_INSERT_LOG_ERRO('PRC_RELATORIO_SUBTOTAIS_MANUAL', SQLCODE, SQLERRM);
        IF DBMS_LOB.ISTEMPORARY(P_RELATORIO)=1 THEN DBMS_LOB.FREETEMPORARY(P_RELATORIO); END IF;
        RAISE;
END PRC_RELATORIO_SUBTOTAIS_MANUAL;
END PKG_PETTRACK_CONSULTA;
