-- Historico imutavel: metadados pesquisaveis e snapshots completos em CLOB.
CREATE TABLE TB_HEALTH_REPORT (
    ID_GERACAO VARCHAR2(36) NOT NULL,
    ID_PET NUMBER NOT NULL,
    ID_SOLICITANTE NUMBER NOT NULL,
    DT_GERACAO TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    DT_CONTEXTO TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    DT_SALVO TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    DS_PROVEDOR VARCHAR2(20) NOT NULL,
    DS_MODELO VARCHAR2(200) NOT NULL,
    DS_VERSAO_PROMPT VARCHAR2(50) NOT NULL,
    ST_SIMULADO CHAR(1) NOT NULL,
    DS_NIVEL_ATENCAO VARCHAR2(20) NOT NULL,
    JS_RELATORIO CLOB NOT NULL,
    JS_CONTEXTO CLOB NOT NULL,
    CONSTRAINT PK_HEALTH_REPORT PRIMARY KEY (ID_GERACAO),
    CONSTRAINT FK_HR_PET FOREIGN KEY (ID_PET) REFERENCES TB_PET(ID_PET),
    CONSTRAINT FK_HR_USUARIO FOREIGN KEY (ID_SOLICITANTE) REFERENCES TB_USUARIO(ID_USUARIO),
    CONSTRAINT CK_HR_PROVEDOR CHECK (DS_PROVEDOR IN ('gemini','mock')),
    CONSTRAINT CK_HR_SIMULADO CHECK ((ST_SIMULADO='S' AND DS_PROVEDOR='mock') OR (ST_SIMULADO='N' AND DS_PROVEDOR='gemini')),
    CONSTRAINT CK_HR_NIVEL CHECK (DS_NIVEL_ATENCAO IN ('BAIXO','MODERADO','ALTO','INDETERMINADO'))
);
CREATE INDEX IX_HR_PET_DATA ON TB_HEALTH_REPORT (ID_PET, DT_SALVO DESC, ID_GERACAO DESC);
